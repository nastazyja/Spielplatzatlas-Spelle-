const kategorien = [
  "Sand & Buddeln",
  "Wasser & Sommer",
  "Outdoor-Spiele",
  "Spielplatz & Ausflug",
  "Natur entdecken"
];

function renderFavoriten() {
  const container = document.getElementById("favoriten-content");
  if (!container) return;

  const sichtbareFavoriten = produktFavoriten.filter(produkt => {
    const hatEinzelbild = typeof produkt.bild === "string" && produkt.bild.trim() !== "";
    const hatBilder = Array.isArray(produkt.bilder) && produkt.bilder.some(bild => typeof bild === "string" && bild.trim() !== "");
    return hatEinzelbild || hatBilder;
  });

  if (!sichtbareFavoriten.length) {
    container.innerHTML = `
      <div class="favoriten-empty">
        <i class="fa-solid fa-leaf" aria-hidden="true"></i>
        <strong>Meine Favoriten werden nach und nach ergänzt.</strong>
        <p style="margin:8px 0 0;">Hier findest du künftig persönlich ausgewählte Produkte für Spielplatz, Garten und kleine Familienabenteuer.</p>
      </div>
    `;
    return;
  }

  const produkteOhneKategorie = sichtbareFavoriten.filter(
    produkt => !produkt.kategorie
  );

  const vorhandeneKategorien = kategorien.filter(kategorie =>
    sichtbareFavoriten.some(produkt => produkt.kategorie === kategorie)
  );

  let html = "";

  // Produkte ohne Kategorie direkt anzeigen
  if (produkteOhneKategorie.length) {
    html += `
      <div class="favoriten-grid">
        ${produkteOhneKategorie.map(renderProdukt).join("")}
      </div>
    `;
  }

  // Kategorien weiterhin vorbereiten, falls du sie später wieder nutzt
  html += vorhandeneKategorien.map(kategorie => {
    const produkte = sichtbareFavoriten.filter(
      p => p.kategorie === kategorie
    );

    return `
      <section class="favoriten-category">
        <h2>${escapeHtml(kategorie)}</h2>
        <div class="favoriten-grid">
          ${produkte.map(renderProdukt).join("")}
        </div>
      </section>
    `;
  }).join("");

  container.innerHTML = html;
}

function renderProdukt(produkt) {
  const bilder = Array.isArray(produkt.bilder) && produkt.bilder.length
    ? produkt.bilder
    : (produkt.bild ? [produkt.bild] : []);

  const galerie = bilder.length
    ? `
      <div class="favoriten-carousel" aria-label="Bildergalerie: ${escapeAttribute(produkt.titel)}">
        <button class="favoriten-arrow favoriten-left" type="button" aria-label="Vorheriges Bild">‹</button>
        ${bilder.map((bild, index) => `
          <img src="${escapeAttribute(bild)}"
               class="${index === 0 ? "active" : ""}"
               ${index === 0 ? "" : 'loading="lazy"'}
               alt="${escapeAttribute(produkt.titel)}${bilder.length > 1 ? ` – Bild ${index + 1}` : ""}">
        `).join("")}
        <button class="favoriten-arrow favoriten-right" type="button" aria-label="Nächstes Bild">›</button>
        <div class="favoriten-dots" aria-hidden="true"></div>
      </div>`
    : `<div class="favoriten-placeholder">Produktbild hier ergänzen</div>`;

  const beschreibung = escapeHtml(produkt.beschreibung)
    .split(/\n\n+/)
    .map(absatz => `<p>${absatz.replace(/\n/g, "<br>")}</p>`)
    .join("");

  return `
    <article class="favoriten-card">
      <div class="favoriten-image-wrap">${galerie}</div>
      <div class="favoriten-body">
        <h3>${escapeHtml(produkt.titel)}</h3>
        <div class="favoriten-description">${beschreibung}</div>
        <div class="favoriten-ad-label">Anzeige · Partnerlink</div>
        <a class="favoriten-button"
           href="${escapeAttribute(produkt.link)}"
           target="_blank"
           rel="nofollow sponsored noopener">
          Bei Amazon ansehen
          <i class="fa-solid fa-arrow-up-right-from-square" aria-hidden="true"></i>
        </a>
      </div>
    </article>
  `;
}

function initFavoritenCarousels() {
  document.querySelectorAll(".favoriten-carousel").forEach(carousel => {
    const images = [...carousel.querySelectorAll("img")];
    const dotsContainer = carousel.querySelector(".favoriten-dots");
    const leftButton = carousel.querySelector(".favoriten-left");
    const rightButton = carousel.querySelector(".favoriten-right");

    if (!images.length || !dotsContainer) return;

    let current = 0;
    dotsContainer.innerHTML = "";

    const dots = images.map((_, index) => {
      const dot = document.createElement("button");
      dot.type = "button";
      dot.className = `favoriten-dot${index === 0 ? " active" : ""}`;
      dot.setAttribute("aria-label", `Bild ${index + 1} anzeigen`);
      dot.addEventListener("click", event => {
        event.stopPropagation();
        showSlide(index);
      });
      dotsContainer.appendChild(dot);
      return dot;
    });

    function showSlide(index) {
      images[current].classList.remove("active");
      dots[current].classList.remove("active");
      current = (index + images.length) % images.length;
      images[current].classList.add("active");
      dots[current].classList.add("active");
    }

    leftButton?.addEventListener("click", event => {
      event.stopPropagation();
      showSlide(current - 1);
    });

    rightButton?.addEventListener("click", event => {
      event.stopPropagation();
      showSlide(current + 1);
    });
  });
}

let favoritenLightboxGallery = [];
let favoritenLightboxIndex = 0;

function initFavoritenLightbox() {
  const lightbox = document.getElementById("favoriten-lightbox");
  const lightboxImg = document.getElementById("favoriten-lightbox-img");
  const closeBtn = lightbox?.querySelector(".favoriten-lightbox-close");
  const leftBtn = lightbox?.querySelector(".favoriten-lightbox-left");
  const rightBtn = lightbox?.querySelector(".favoriten-lightbox-right");

  if (!lightbox || !lightboxImg) return;

  const showLightboxImage = () => {
    const img = favoritenLightboxGallery[favoritenLightboxIndex];
    if (!img) return;
    lightboxImg.src = img.src;
    lightboxImg.alt = img.alt;
  };

  document.querySelectorAll(".favoriten-carousel").forEach(carousel => {
    const images = [...carousel.querySelectorAll("img")];

    images.forEach((img, index) => {
      img.addEventListener("click", () => {
        favoritenLightboxGallery = images;
        favoritenLightboxIndex = index;
        showLightboxImage();
        lightbox.classList.add("open");
        document.body.classList.add("favoriten-lightbox-open");
      });
    });
  });

  const closeLightbox = () => {
    lightbox.classList.remove("open");
    document.body.classList.remove("favoriten-lightbox-open");
  };

  closeBtn?.addEventListener("click", closeLightbox);
  leftBtn?.addEventListener("click", () => {
    favoritenLightboxIndex = (favoritenLightboxIndex - 1 + favoritenLightboxGallery.length) % favoritenLightboxGallery.length;
    showLightboxImage();
  });
  rightBtn?.addEventListener("click", () => {
    favoritenLightboxIndex = (favoritenLightboxIndex + 1) % favoritenLightboxGallery.length;
    showLightboxImage();
  });

  lightbox.addEventListener("click", event => {
    if (event.target === lightbox) closeLightbox();
  });

  document.addEventListener("keydown", event => {
    if (!lightbox.classList.contains("open")) return;
    if (event.key === "Escape") closeLightbox();
    if (event.key === "ArrowLeft") leftBtn?.click();
    if (event.key === "ArrowRight") rightBtn?.click();
  });
}

function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function escapeAttribute(value) {
  return escapeHtml(value);
}

window.addEventListener("DOMContentLoaded", () => {
  renderFavoriten();
  initFavoritenCarousels();
  initFavoritenLightbox();
});
